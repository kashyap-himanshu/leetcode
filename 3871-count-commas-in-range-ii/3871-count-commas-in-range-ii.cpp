class Solution {
public:
    long long countCommas(long long n) {
        if(n<1000)return 0;
        long long ans=0;
        if(n>=1000 && n<=999999)
        ans=ans+(n-1000)+1;
        if(n>999999 && n<=999999999){
        ans=ans+(999999-1000)+1;
        ans=ans+((n-1000000)+1)*2;}
        if(n>999999999 && n<=999999999999){
             ans=ans+(999999-1000)+1;
        ans=ans+((999999999-1000000)+1)*2;
        ans=ans+((n-1000000000)+1)*3;
        }
        if(n>999999999999 && n<=999999999999999){
              ans=ans+(999999-1000)+1;
        ans=ans+((999999999-1000000)+1)*2;
        ans=ans+((999999999999-1000000000)+1)*3;
        ans=ans+((n-1000000000000)+1)*4;

        }
        if(n>999999999999999 && n<=9999999999999999){
                ans=ans+(999999-1000)+1;
        ans=ans+((999999999-1000000)+1)*2;
         ans=ans+((999999999999-1000000000)+1)*3;
        ans=ans+((999999999999999-1000000000000)+1)*4;
        ans=ans+((n-1000000000000000)+1)*5;
        }
        return ans;


        
    }
};